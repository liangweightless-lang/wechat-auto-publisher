    @classmethod
    def retrieve_relevant_history(cls, query: str, max_chars: int = 3000) -> str:
        """
        基于查询文本智能检索最匹配的地缘战史与武器档案
        :param query: 用户输入的话题或抓取的新闻内容
        :param max_chars: 最大返回字符数
        :return: 结构化历史档案背景
        """
        if not query:
            return ""

        query_clean = query.lower()
        scored_archives = []

        for item in cls.HISTORICAL_ARCHIVES:
            score = 0
            for kw in item["keywords"]:
                if kw in query_clean:
                    score += 2
                # 模糊匹配
                if any(char in query_clean for char in kw if len(kw) > 1):
                    score += 0.5

            if score > 0:
                scored_archives.append((score, item))

        # 按相关度从高到低排序
        scored_archives.sort(key=lambda x: x[0], reverse=True)

        if not scored_archives:
            # 如果没有直接关键词命中，默认返回中东与导弹防御基础档案
            scored_archives = [(1, cls.HISTORICAL_ARCHIVES[0]), (1, cls.HISTORICAL_ARCHIVES[1])]

        result_texts = []
        current_len = 0

        for score, arc in scored_archives:
            content = f"【历史纵深与装备档案专题：{arc['title']}】\n{arc['dossier'].strip()}\n"
            if current_len + len(content) > max_chars:
                break
            result_texts.append(content)
            current_len += len(content)

        logger.info(f"历史档案检索完成，命中 {len(result_texts)} 篇战史与技术底座资料 (字符数: {current_len})")
        return "\n".join(result_texts)

    def retrieve(self, query: str, top_k: int = 5):
        """实例方法兼容"""
        return [self.retrieve_relevant_history(query)]

    def format_for_prompt(self, docs):
        """格式化返回"""
        if isinstance(docs, str):
            return docs
        return "\n\n".join(docs)
